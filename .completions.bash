### Wrappers

# git shells out to the subcommand to enumerate its flags, and $HOME is not a
# repository -- the dotfiles repo is bare at ~/.dotfiles. Without this,
# `dot commit --a<TAB>` completes only subcommand names.
if declare -F __git_complete >/dev/null; then
	_dot_main() {
		GIT_DIR=$HOME/.dotfiles GIT_WORK_TREE=$HOME __git_main "$@"
	}
	__git_complete dot _dot_main
fi

# The agent entrypoints take `nono run` arguments up to `--`, so rewrite the
# line and hand it to nono's own completion.
if declare -F _nono >/dev/null; then
	_agent_complete() {
		if [[ " ${COMP_WORDS[*]:1:COMP_CWORD-1} " == *" -- "* ]]; then
			return
		fi
		COMP_WORDS=(nono run "${COMP_WORDS[@]:1}")
		((COMP_CWORD += 1))
		_nono nono "$2" "$3"
	}

	# Same options nono registers itself with: `_nono` emits no COMPREPLY for
	# path-valued flags and leans on `-o default` for the filename fallback.
	for _c in ncl npi nop; do
		if declare -F "$_c" >/dev/null; then
			complete -o bashdefault -o default -o nosort -F _agent_complete "$_c"
		fi
	done
	unset _c
elif command -v nono &>/dev/null; then
	echo ".completions.bash: nono completion no longer defines _nono" >&2
fi
