### Shipped as files
#
# Paths are from a podman sweep of debian, ubuntu, fedora, arch, alpine and
# NixOS; XDG_DATA_DIRS was empty on every one. The framework must come first.

# Load-bearing on Debian and Ubuntu, which ship the framework but leave the
# block in /etc/bash.bashrc commented out. VERSINFO is assigned at the top of
# the framework itself; _init_completion is the wrong test, living in a compat
# shim upstream deprecated and a distro need not load.
if [ -z "${BASH_COMPLETION_VERSINFO[*]-}" ]; then
	if [ -f /usr/share/bash-completion/bash_completion ]; then
		source /usr/share/bash-completion/bash_completion
	fi
fi

# Two blocks, not one elif chain: completion and prompt are different files and
# we want both.
if ! declare -F __git_main >/dev/null; then
	if [ -f /usr/share/bash-completion/completions/git ]; then
		source /usr/share/bash-completion/completions/git
	elif [ -f /run/current-system/sw/share/bash-completion/completions/git ]; then
		source /run/current-system/sw/share/bash-completion/completions/git
	fi
fi

# Not a completion, but git ships __git_ps1 alongside them. Alpine packages no
# copy; Debian, Ubuntu and openSUSE keep theirs outside every data root and
# load it from /etc/bash_completion.d, which is what the guard catches.
if ! declare -F __git_ps1 >/dev/null; then
	if [ -f /usr/share/git-core/contrib/completion/git-prompt.sh ]; then
		source /usr/share/git-core/contrib/completion/git-prompt.sh
	elif [ -f /usr/share/git/completion/git-prompt.sh ]; then
		source /usr/share/git/completion/git-prompt.sh
	elif [ -f /run/current-system/sw/share/bash-completion/completions/git-prompt.sh ]; then
		source /run/current-system/sw/share/bash-completion/completions/git-prompt.sh
	fi
fi

